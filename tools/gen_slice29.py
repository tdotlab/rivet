#!/usr/bin/env python3
"""Slice-29 generator: ZERO INCBIN -- the finish.

Reads every INCBIN line in src/banks.asm, verifies FIRST that the ROM
bytes in each range are all $ff (refuses to convert any range that is
not all-$ff -- exits non-zero and leaves src/banks.asm untouched),
then rewrites src/banks.asm with each INCBIN replaced by a labelled
RGBDS `ds $len, $ff` plus a comment naming the bank and range, e.g.:

    ; Bank 4 $76b0-$7fff $ff padding
    ds $0950, $ff

The coordinator independently verified (2026-11-25) that all 74,129
remaining INCBIN bytes are $ff padding; this script re-verifies that
claim from the ROM bytes before touching anything, so a stale or wrong
premise fails loudly instead of silently baking zeros into the build.

Idempotent: if src/banks.asm has no INCBIN lines left it reports 0
converted and exits 0.

Run: python3 tools/gen_slice29.py   (from the project root)
"""
import re
import sys

ROM = "roms/Donkey_Kong_World_Rev1_SGB.gb"
BANKS = "src/banks.asm"

INCBIN_RE = re.compile(
    r'^(\s*)INCBIN\s+"[^"]+"\s*,\s*\$([0-9a-fA-F]+)\s*,\s*\$([0-9a-fA-F]+)\s*$'
)


def bank_addr(off):
    """ROM file offset -> (bank, address-in-bank-window)."""
    bank = off // 0x4000
    if bank == 0:
        return 0, off
    return bank, 0x4000 + (off % 0x4000)


def main():
    rom = open(ROM, "rb").read()
    lines = open(BANKS).read().splitlines(keepends=True)

    # Pass 1: collect + verify every INCBIN range against the ROM.
    jobs = []  # (line_index, off, length)
    for i, line in enumerate(lines):
        m = INCBIN_RE.match(line.rstrip("\n"))
        if m:
            off = int(m.group(2), 16)
            ln = int(m.group(3), 16)
            jobs.append((i, off, ln))

    if not jobs:
        print("gen_slice29: no INCBIN lines left in src/banks.asm (0 converted)")
        return 0

    total = 0
    for i, off, ln in jobs:
        chunk = rom[off:off + ln]
        if len(chunk) != ln:
            print(f"REFUSE: INCBIN at line {i+1} offset ${off:05x} len ${ln:x} "
                  f"runs past the end of the ROM", file=sys.stderr)
            return 1
        bad = [j for j, b in enumerate(chunk) if b != 0xFF]
        if bad:
            first = bad[0]
            print(f"REFUSE: INCBIN at line {i+1} offset ${off:05x} len ${ln:x} "
                  f"is NOT all-$ff: byte {first} (${off+first:05x}) "
                  f"is ${chunk[first]:02x} ({len(bad)} non-$ff bytes total)",
                  file=sys.stderr)
            return 1
        total += ln
    print(f"gen_slice29: verified {len(jobs)} INCBIN ranges, "
          f"{total} bytes, all $ff in the ROM")

    # Pass 2: rewrite.
    out = []
    for i, line in enumerate(lines):
        m = INCBIN_RE.match(line.rstrip("\n"))
        if not m:
            out.append(line)
            continue
        off = int(m.group(2), 16)
        ln = int(m.group(3), 16)
        bank, addr = bank_addr(off)
        end = addr + ln - 1
        indent = m.group(1)
        out.append(f"{indent}; Bank {bank} ${addr:04x}-${end:04x} $ff padding\n")
        out.append(f"{indent}ds ${ln:04x}, $ff\n")

    # Header: record the conversion so a future reader knows why there
    # is no INCBIN here anymore (gen_banks.py was patched the same day
    # to emit ds lines instead of INCBIN for these gaps).
    text = "".join(out)
    text = text.replace(
        "; GENERATED by tools/gen_banks.py -- do not hand-edit.\n"
        "; Raw bank data, pulled in as INCBIN from the local ROM at build time.\n"
        "; Curated ranges live in src/ (see CARVED in tools/gen_banks.py).\n",
        "; GENERATED by tools/gen_banks.py -- do not hand-edit.\n"
        "; $ff padding tails, emitted as `ds $len, $ff` (slice 29).\n"
        "; Slice 29 converted the last INCBIN lines (all $ff padding,\n"
        "; verified against the ROM by tools/gen_slice29.py) to ds, so\n"
        "; src/ now has ZERO INCBIN. Curated ranges live in src/\n"
        "; (see CARVED in tools/gen_banks.py).\n",
        1,
    )
    open(BANKS, "w").write(text)
    print(f"gen_slice29: converted {len(jobs)} ranges ({total} bytes) "
          f"to ds $len, $ff in src/banks.asm")
    return 0


if __name__ == "__main__":
    sys.exit(main())
