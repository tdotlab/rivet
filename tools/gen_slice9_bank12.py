#!/usr/bin/env python3
"""Slice 9 generator: bank 12 ($0c) $5917-$5dbc data + credits text.

Bank-12 code ends at $5916 (`ret`, slice 3); everything after is data:
  $5917-$5937: repeating `4a 4e 4b 4c 4d` pattern (continues the $5917
    pattern slice 3 noted; structure unresolved).
  $5938-$5977: structured records (`05 07 00 4a 4a 4a ...`, groups of
    7 bytes starting with a small count) -- unresolved.
  $5978-$599f: coordinate-like pairs (`88 28 88 28 ... 70 28`) then
    zeros to $59a0 -- unresolved, likely credits-screen sprite pos.
  $59a0-$5dab: credits text (ASCII with $00 padding between lines;
    the `_[\\]... NINTENDO` lines are tile-index sequences that render
    as the (C) symbol + NINTENDO). Emitted as hex `db` so the exact
    bytes (including padding and backslashes) are preserved; each
    line is annotated with its readable text. Ends $5dab; $5dbc+
    ("        defghi"...) is font/tile data, stays INCBIN.

Outputs: src/bank12slice9.asm. Regenerate with:
  python3 tools/gen_slice9_bank12.py
then update tools/gen_banks.py CARVED (12: [..., (0x4000, 0x5DBC)]),
regenerate src/banks.asm, add INCLUDE "bank12slice9.asm" to
src/main.asm, and rebuild (byte-match arbitrates).
"""
import re

ROM = "roms/Donkey_Kong_World_Rev1_SGB.gb"
BANK12 = 12
DATA_LO, DATA_HI = 0x5917, 0x59A0
CRED_LO, CRED_HI = 0x59A0, 0x5DBC


def file_off(bank, addr):
    return bank * 0x4000 + (addr - 0x4000)


def db_lines(rom, lo, hi, per_line=16):
    out = []
    addr = lo
    while addr < hi:
        n = min(per_line, hi - addr)
        chunk = rom[file_off(BANK12, addr):file_off(BANK12, addr) + n]
        out.append((addr, chunk))
        addr += len(chunk)
    return out


def emit(rom):
    out = ["; Slice 9: Bank $0c $5917-$5dbc -- data + credits text.",
           "; Code ends at $5916 (ret, slice 3); nothing calls into",
           "; $5917+ (verified: no call/jp/rst-$08 target in $5917-$5dbc",
           "; anywhere in the ROM; the bytes decode as data/text, not",
           "; code). The $59a0+ text is the end credits (Executive",
           "; Producer Hiroshi Yamauchi, Producer Shigeru Miyamoto, ...).",
           "; Generated by tools/gen_slice9_bank12.py from the ROM bytes.",
           "; Byte-match (`make`) arbitrates."]
    out.append('SECTION "Bank $0c $5917-$599f data", ROMX[$5917], BANK[12]')
    for addr, chunk in db_lines(rom, DATA_LO, DATA_HI):
        note = ""
        if addr == DATA_LO:
            note = " ; repeating 4a/4b/4c/4d/4e pattern"
        elif addr == 0x5938:
            note = " ; structured records begin"
        elif addr == 0x5978:
            note = " ; coordinate-like pairs"
        out.append("    db " + ", ".join(f"${b:02x}" for b in chunk) + note)
    out.append('SECTION "Bank $0c $59a0-$5dbb credits", ROMX[$59a0], BANK[12]')
    # Annotate each text line with its readable content.
    seg = rom[file_off(BANK12, CRED_LO):file_off(BANK12, CRED_HI)]
    for m in re.finditer(rb"[\x20-\x7e]{3,}", seg):
        s, e = CRED_LO + m.start(), CRED_LO + m.end()
        out.append(f"    ; ${s:04x}: {m.group().decode('ascii')!r}")
    for addr, chunk in db_lines(rom, CRED_LO, CRED_HI):
        out.append("    db " + ", ".join(f"${b:02x}" for b in chunk))
    return "\n".join(out) + "\n"


def main():
    rom = open(ROM, "rb").read()
    header = ("; DO NOT HAND-EDIT the code bodies in this file -- regenerate with\n"
              ";   python3 tools/gen_slice9_bank12.py\n"
              "; after changing the generator config. Entry labels and comments\n"
              "; may be added by hand above a generated block, not inside it.\n\n")
    with open("src/bank12slice9.asm", "w") as f:
        f.write(header + emit(rom))
    print("wrote src/bank12slice9.asm")


if __name__ == "__main__":
    main()
