def gaps(bank):
    """Uncarved intervals of bank `bank` as (lo, hi) in $4000-$7fff."""
    carved = sorted(CARVED.get(bank, []))
    out, cur = [], 0x4000
    for lo, hi in carved:
        if lo > cur:
            out.append((cur, lo))
        cur = max(cur, hi)
    if cur < 0x8000:
        out.append((cur, 0x8000))
    return out


