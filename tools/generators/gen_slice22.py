#!/usr/bin/env python3
"""Slice-22 generator: bank 4 is tile graphics data, not code.

Survey (see tools/surveys/survey22_bank4.py for the reproducible numbers):
  * Only two `ld a,$04; rst $10` sites exist in the whole ROM, both in
    bank 0, and both use bank 4 purely as a copy source -- never as
    code:
      - bank-0 $2d2d (routine $2cc1, called from $0e72): HL=$5f30,
        DE=$8480, C=$80, call $106e (MemcpyC) -- 128 bytes = 8 tiles
        to VRAM $8480.
      - bank-0 $356f LoadTilesFromBank4 (called from bank-1 $4e20):
        HL=$67b0, DE=$8000, BC=$0300, call MemcpyBC -- 768 bytes =
        48 tiles to VRAM $8000. (The task brief said 128 bytes via
        $106e for both; that is wrong for $356f -- $106e is MemcpyC
        and $356f uses MemcpyBC with BC=$0300.)
  * No call/jp/jr/table target into bank 4 exists anywhere: the two
    mappings are transient copy windows (bank restored immediately
    after -- `pop af; rst $10` at $2d40, `ld a,$01; rst $10` at
    $357e), so no bank-4 byte can ever execute.
  * The bytes are 2bpp tiles: $4000 starts with a blank tile, then
    clean glyphs (tiles 1-7 render as 0/1/2/3/4/5/6-ish digit
    shapes); $4000-$76af is exactly 14,000 bytes = 875 tiles of 16
    bytes; $5f30 and $67b0 are 16-byte aligned (tiles 499 and 635).
    Opcode counts per 4 KiB are at noise level (ret 0-6, call 0-1,
    jp 0-6, no rst $10, no jp (hl)); gb_rd walks from $4000/$5f30/
    $67b0 hit invalid opcodes ($fc/$10) within 102-1,393 instrs --
    linear decode of tile bytes, not code.
  * Last non-$ff byte is at $76af; $76b0-$7fff is all $ff padding
    (stays INCBIN).

So the carve emits $4000-$76af as db, one 16-byte tile per line,
split into sections at the two proven copy sources. No code is
claimed anywhere in the bank. The $1832-handler `ld hl,$5f30` sites
(bank-0 $18aa/$1965/$198e/$1b72) only STORE the address $5f30 into
the $da71 pointer table -- which bank is mapped when that pointer
is dereferenced is unresolved, and the $10dd consumer maps bank
$0b/$1d, so those are NOT claimed as bank-4 reads.

Door / clear chain: bank 4 has no code, so it writes no timer
($ff90) and no [$c105]; no new door lead, no completion attempt
(same NO-GO as slices 15-21).

Regenerate with: python3 tools/generators/gen_slice22.py
Outputs: src/banks/bank4.asm (new file).
Also update tools/generators/gen_banks.py CARVED (bank 4) and regenerate
src/banks.asm; add INCLUDE "bank4.asm" to src/main.asm.
The outputs are CHECKED IN; rerun after changing the config.
"""
import sys

sys.path.insert(0, "tools")
from gb_rd import file_off  # noqa: E402

ROM = "roms/Donkey_Kong_World_Rev1_SGB.gb"

# (lo, hi, title, label) -- hi inclusive; one tile (16 bytes) per line.
SECTIONS = [
    (0x4000, 0x5F2F, "Bank 4 tiles $4000-$5f2f", None),
    (0x5F30, 0x5FAF, "Bank 4 tiles $5f30-$5faf (128-byte block copied "
     "to VRAM $8480 by bank-0 $2d2d via MemcpyC $106e)", "Bank4_Tiles_5F30"),
    (0x5FB0, 0x67AF, "Bank 4 tiles $5fb0-$67af", None),
    (0x67B0, 0x6AAF, "Bank 4 tiles $67b0-$6aaf (768-byte block copied "
     "to VRAM $8000 by LoadTilesFromBank4 $356f via MemcpyBC)",
     "Bank4_Tiles_67B0"),
    (0x6AB0, 0x76AF, "Bank 4 tiles $6ab0-$76af", None),
]


def emit_tiles(rom, lo, hi, title, label):
    out = [f"; Slice 22: {title} -- bank 4 ${lo:04x}-${hi:04x}.",
           "; 2bpp tile data (16 bytes per tile), emitted as db, one",
           "; tile per line. Generated by tools/generators/gen_slice22.py from",
           "; the ROM bytes. Byte-match (`make`) arbitrates.",
           f'SECTION "{title}", ROMX[${lo:04x}], BANK[4]']
    if label:
        out.append(f"{label}::")
    addr = lo
    while addr <= hi:
        chunk = [rom[file_off(4, a)] for a in range(addr, addr + 16)]
        tile_no = (addr - 0x4000) // 16
        out.append("    db " + ", ".join(f"${b:02x}" for b in chunk)
                   + f"  ; tile {tile_no}")
        addr += 16
    return "\n".join(out) + "\n"


def main():
    rom = open(ROM, "rb").read()
    # Assertions the survey rests on.
    assert rom[file_off(4, 0x76AF)] != 0xFF, "last non-$ff moved"
    assert all(b == 0xFF for b in
               (rom[file_off(4, a)] for a in range(0x76B0, 0x8000))), \
        "$76b0-$7fff is not all $ff"
    assert (0x76B0 - 0x4000) % 16 == 0, "carve end not tile-aligned"
    assert (0x5F30 - 0x4000) % 16 == 0 and (0x67B0 - 0x4000) % 16 == 0, \
        "copy sources not tile-aligned"
    parts = []
    for lo, hi, title, label in SECTIONS:
        parts.append(emit_tiles(rom, lo, hi, title, label))
    total = sum(hi - lo + 1 for lo, hi, _, _ in SECTIONS)
    assert total == 0x36B0, f"carve covers {total} bytes, want 0x36b0"
    with open("src/banks/bank4.asm", "w") as f:
        f.write("\n".join(parts))
    print(f"wrote src/banks/bank4.asm: {total} bytes, "
          f"{total // 16} tiles, bank 4 $4000-$76af", file=sys.stderr)


if __name__ == "__main__":
    main()
