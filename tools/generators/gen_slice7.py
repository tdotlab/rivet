#!/usr/bin/env python3
"""Slice-7 generator: carve bank 0 $17eb-$1d06, bank 11 $4000 sprite
pointer table, and bank 18 $4934 stage table.

Bank 0 $17eb-$1d06 (584 instructions, 4 seeds):
  * $17eb SpriteRecordDispatch: gated on [$c200]!=0; A=[$c201]>>1, and
    if it differs from [$ddb3], dispatch via rst $08 at $1832.
    Called from $0a95 (state-16 timer 28).
  * $1805 SpriteRecordDispatchB: same dispatch, ungated (A=[$c201]>>1).
    Called from $0886/$08d8/$090f/$0986/$09b9/$09c6/$0a18.
  * $1832 Rst08Dispatch: rst $08 with a 44-entry dw table ($1833-$188a,
    handlers $188b-$1c28 plus $1d29 `ret` as entries 15 and 24). The
    table entries are ROM0 addresses, so this carve needed the bank-0
    fix in tools/gb_rd.py (walk() used to reject ROM0 table entries).
  * $1c29 BuildAttrMap: reads exactly 13 bytes from the $1c7d table
    (C=0..12), indexes $ddf5/$d93d, writes VRAM pointers into $daf5
    and C+1 into $da4f+C, then tail-jumps to banked $5d21.
    Called from $076b (state-16 timer 0/1, level-load path).
  * $1c8a LoadStagePtrWrapper: call $1c91, switch bank to $17, ret.
  * $1c91 LoadStagePtr: switches to bank $1e, calls $1cf7, then loads
    the stage's state-table pointer from bank-$1e $64e5 (16-byte
    stride, [$c853]/[$c854]/[$c855] overrides for D==0/1/9) into
    [$da5f]/[$da60] (wStatePtrLo). Jumps to $1d07 (InitStatePtrLo)
    when the record byte is 0.
  * $1cf7 IncAttrCounter: increments the two-nibble counter at $da4d.

Bank 11 $4000-$4100: 128 dw sprite-pointer table, the $112c table
(bank $0b/$1d $4000, indexed by 2*record[0], then +2*record[1]).
Entries 0-87 are a clean increasing run ($4269-$591e, with pair
repeats); 88-95 and 98-101 are $4200 (the empty/default block);
114-119 point at $53xx-$71xx. Extent 128 is inferred -- the $4200
runs are consistent with unused slots, and every word is a plausible
pointer -- not verified against live record[0] values.

Bank 18 $4934-$4c83: 106 8-byte db records, the stage table read by
$271e/$4586/$4807 (base $4934, stride 8, index B). Entries 0-100 are
verified (B<=100 from the queue's C==1 entries); entries 101-105
are inferred -- same texture, and 106 matches bank 5's 106 stage
pointers. RECORD LAYOUT UNRESOLVED (see PROGRESS.md): the naive
(world=[+0], stage=[+6]) reading gives world=$03/stage=$ee for B=0,
but the live map visit shows world=1/stage=1 -- the world/stage are
finalized by stream processing during state-20 timer 1 (bank 2/3 +
bank-11 table handlers, uncarved). The bytes are carved as db, with
no field claims.

Regenerate with: python3 tools/generators/gen_slice7.py
Outputs: src/banks/bank0slice7.asm src/banks/bank11.asm src/banks/bank18.asm (new
files); regenerates src/banks.asm via tools/generators/gen_banks.py after
updating its CARVED map. The outputs are CHECKED IN.
"""
import re
import sys

sys.path.insert(0, "tools")
from gb_rd import walk, file_off  # noqa: E402

ROM = "roms/Donkey_Kong_World_Rev1_SGB.gb"

LO, HI = 0x17EB, 0x1D06
SEEDS = [0x17EB, 0x1805, 0x1C29, 0x1C8A]

LABELS = {
    0x17EB: "SpriteRecordDispatch",   # gated on [$c200]!=0; $1832 on change
    0x1805: "SpriteRecordDispatchB",  # ungated; $1832 on change
    0x1832: "Rst08Dispatch",          # rst $08, 44-entry table at $1833
    0x1C29: "BuildAttrMap",           # 13 bytes from $1c7d -> $daf5/$da4f
    0x1C8A: "LoadStagePtrWrapper",    # call $1c91, bank $17, ret
    0x1C91: "LoadStagePtr",           # bank $1e $64e5 -> [$da5f]/[$da60]
    0x1CF7: "IncAttrCounter",         # two-nibble counter at $da4d
}

# Uncovered data runs inside the bank-0 carve: (addr) -> comment line.
DATA_COMMENTS = {
    0x1C7D: "; 13-byte index table, read by BuildAttrMap ($1c29, C=0..12).",
}


def jr_label(tgt):
    return f"jr_000_{tgt:04x}"


def jr_targets_in(instrs, lo, hi):
    out = set()
    for addr, (ln, text, kind, tgt) in instrs.items():
        if kind == "jr" and isinstance(tgt, int) and lo <= tgt <= hi:
            out.add(tgt)
    return out


def fmt_instr(addr, text, kind, tgt, lo, hi, jr_targets):
    if addr in LABELS:
        label = f"{LABELS[addr]}::"
    elif addr in jr_targets:
        label = f"{jr_label(addr)}:"
    else:
        label = None
    if kind == "jr" and isinstance(tgt, int) and lo <= tgt <= hi:
        if tgt in LABELS:
            tgt_label = LABELS[tgt]
        else:
            tgt_label = jr_label(tgt)
        text = re.sub(r"\$[0-9a-f]{4}$", tgt_label, text)
    line = f"    {text:<48} ; ${addr:04x}"
    return (label + "\n" + line) if label else line


def emit_bank0(rom, instrs, rst08):
    out = ["; Slice 7: Bank 0 $17eb-$1d06 -- sprite-record dispatchers,",
           "; the $1832 rst-$08 table (44 entries), BuildAttrMap, and",
           "; the LoadStagePtr bank-$1e trampoline.",
           "; Generated by tools/generators/gen_slice7.py from the ROM bytes via",
           "; tools/gb_rd.py (recursive descent; the $1832 table needed",
           "; the bank-0 rst-$08 fix in gb_rd.py -- ROM0 entries).",
           "; Byte-match (`make`) arbitrates.",
           'SECTION "Bank 0 $17eb-$1d06", ROM0[$17eb]']
    jr_targets = jr_targets_in(instrs, LO, HI)
    for addr, (ln, text, kind, tgt) in instrs.items():
        if kind in ("call", "jump", "jr") and isinstance(tgt, int) \
                and LO <= tgt <= HI and tgt not in instrs:
            print(f"ERROR: ${addr:04x} {text} targets ${tgt:04x}, "
                  f"not a decoded instruction", file=sys.stderr)
            sys.exit(1)
    for site, tbl in rst08.items():
        if not (LO <= site <= HI):
            continue
        for i, w in enumerate(tbl):
            if 0x0000 <= w <= 0x3FFF and LO <= w <= HI and w not in instrs:
                print(f"ERROR: rst $08 at ${site:04x} entry {i} -> "
                      f"${w:04x}, not decoded", file=sys.stderr)
                sys.exit(1)
    addr = LO
    while addr <= HI:
        if addr in instrs:
            ln, text, kind, tgt = instrs[addr]
            if kind == "rst08":
                tbl = rst08[addr]
                out.append(f"    {'rst $08':<48} ; ${addr:04x}")
                for i, w in enumerate(tbl):
                    out.append(f"    {'dw $%04x' % w:<48} ; entry {i}")
                addr += 1 + 2 * len(tbl)
                continue
            out.append(fmt_instr(addr, text, kind, tgt, LO, HI, jr_targets))
            addr += ln
        else:
            run = []
            while addr <= HI and addr not in instrs \
                    and not any(s < addr < s + 1 + 2 * len(t)
                                for s, t in rst08.items()):
                run.append(rom[file_off(0, addr)])
                addr += 1
            if not run:
                print(f"ERROR: ${addr:04x}: fell into an rst-$08 table "
                      f"outside the rst08 branch", file=sys.stderr)
                sys.exit(1)
            if run and (addr - len(run)) in DATA_COMMENTS:
                out.append(DATA_COMMENTS[addr - len(run)])
            for j in range(0, len(run), 8):
                chunk = run[j:j + 8]
                out.append("    db " + ", ".join(f"${b:02x}" for b in chunk))
    return "\n".join(out) + "\n"


def emit_bank11(rom):
    """Bank 11 $4000-$4200: 256 dw sprite-pointer table.

    Slice 18 CORRECTS slice 7's 128-entry extent to 256 (VERIFIED, not
    inferred): $112c indexes by the full record byte 0 (C = byte0,
    HL = $4000 + 2*C, no masking); live record byte-0 values across
    all 101 surveyed stages reach 229 (tools/surveys/survey18_records.py);
    all 256 words are plausible pointers ($4200-$7xxx), none points
    into $4100-$41ff, and 35 are $4200 (the empty/default block).
    Entries 0-87 are a clean increasing run ($4269-$591e, pair
    repeats); 88-95 and 98-101 are $4200; 114-119 point at
    $53xx-$71xx. Generated by tools/generators/gen_slice7.py from the ROM bytes."""
    out = ["; Slice 7: Bank 11 $4000 sprite-pointer table -- 256 dw.",
           "; The $112c table (bank $0b/$1d $4000, indexed by",
           "; 2*record[0], then +2*record[1]). Entries 0-87 are a clean",
           "; increasing run ($4269-$591e, pair repeats); 88-95 and",
           "; 98-101 are $4200 (the empty/default block); 114-119 point",
           "; at $53xx-$71xx. Extent 256 VERIFIED slice 18 (see the",
           "; emit_bank11 docstring in tools/generators/gen_slice7.py): $112c uses",
           "; the full record byte 0 as the index, and live record[0]",
           "; values reach 229 across the 101 surveyed stages.",
           "; Generated by tools/generators/gen_slice7.py from the ROM bytes.",
           'SECTION "Bank 11 $4000 sprite table", ROMX[$4000], BANK[11]']
    off = file_off(11, 0x4000)
    for i in range(256):
        w = rom[off + 2 * i] | (rom[off + 2 * i + 1] << 8)
        out.append(f"    {'dw $%04x' % w:<48} ; entry {i}")
    return "\n".join(out) + "\n"


def emit_bank18(rom):
    """Bank 18 $4934-$4c83: 106 8-byte db stage-table records."""
    out = ["; Slice 7 (CORRECTED slice 8): Bank 18 DECIMAL ($12) $4934 -- 106",
           "; 8-byte records of UNKNOWN role. This is NOT the stage table:",
           "; slice 7 mislabelled it by a decimal/hex slip. The real stage",
           "; table is bank $18 HEX (decimal 24), carved in src/banks/bank24.asm",
           "; (tools/generators/gen_slice8.py). The bytes here are correct for bank $12;",
           "; only the claim was wrong. Entries 0-100 / 101-105 split below",
           "; is the slice-7 guess and means nothing now.",
           "; Generated by tools/generators/gen_slice7.py from the ROM bytes.",
           'SECTION "Bank 18 $4934 records (NOT the stage table)", ROMX[$4934], BANK[18]']
    off = file_off(18, 0x4934)
    for i in range(106):
        chunk = rom[off + 8 * i: off + 8 * i + 8]
        note = " ; entry %d" % i
        if i >= 101:
            note += " (inferred)"
        out.append("    db " + ", ".join(f"${b:02x}" for b in chunk) + note)
    return "\n".join(out) + "\n"


def main():
    rom = open(ROM, "rb").read()
    reached, rst08, notes = walk(0, SEEDS)
    # $1c7a `jp $5d21` is a tail-jump into banked code -- outside ROM0,
    # so the walk rightly stops there.
    notes = [n for n in notes if "$5d21 outside ROM0" not in n]
    assert not notes, notes
    covered = set()
    for s, (ln, _t, _k, _tg) in reached.items():
        covered.update(range(s, s + ln))
    for site, tbl in rst08.items():
        covered.update(range(site, site + 1 + 2 * len(tbl)))
    uncovered = [a for a in range(LO, HI + 1) if a not in covered]
    assert uncovered == list(range(0x1C7D, 0x1C8A)), \
        f"unexpected uncovered bytes: {[hex(a) for a in uncovered[:8]]}"
    header = ("; DO NOT HAND-EDIT the code bodies in this file -- regenerate with\n"
              ";   python3 tools/generators/gen_slice7.py\n"
              "; after changing the generator config. Entry labels and comments\n"
              "; may be added by hand above a generated block, not inside it.\n\n")
    with open("src/banks/bank0slice7.asm", "w") as f:
        f.write(header + emit_bank0(rom, reached, rst08))
    print(f"wrote src/banks/bank0slice7.asm ({len(reached)} instructions, "
          f"rst08 $1832: {len(rst08[0x1832])} entries)")
    with open("src/banks/bank11.asm", "w") as f:
        f.write(header + emit_bank11(rom))
    print("wrote src/banks/bank11.asm (256 dw)")
    with open("src/banks/bank18.asm", "w") as f:
        f.write(header + emit_bank18(rom))
    print("wrote src/banks/bank18.asm (106 records)")


if __name__ == "__main__":
    main()
