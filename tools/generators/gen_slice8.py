#!/usr/bin/env python3
"""Slice 8 generator: the REAL stage table carve (bank $18 hex = 24 decimal).

Slice 7 carved bank 18 DECIMAL ($12) $4934 as "the stage table" -- a
decimal/hex slip. The game reads the stage table from bank $18 (the
`ld a,$18; rst $10` at $26f6 is hex $18 = 24 decimal), and gb_watch
proved it live: the (world,stage) writes at $2745/$2750 during the
state-20 timer-1 visit read record B=0 as (1,1), which matches bank
$18's record 0 `01 80 20 60 80 01 01 05`, not bank $12's
`03 44 01 f0 f0 f3 ee 40`.

Layout (verified: code at $271e-$2750 + live watch + table texture):
  [+0] world (1-9 for B=0..96); [+5] duplicates [+0] for B<97
  [+6] stage-in-world (1-16 for B=0..96)
  [+1..+4] coordinate-like pairs, unresolved
  [+7] small value (4-40 for B<97), unresolved
  B=0..96 are clean stage records (worlds 1-9, stages 1-8/12/16);
  B=97..105 do NOT fit the pattern (worlds 0/110/62/28...) and their
  role is unresolved -- the queue does contain C==1 entries with
  B=97..100, so they may be reachable, but no live visit has shown it.
The $288e prev-record fallback (fires when ([$c70f]&3)==3) can read the
previous record instead; the bit-0 setter of [$c70f] is still unfound,
so the fallback's exact trigger is open.

Also fixes the slice-7 mislabel in place: src/banks/bank18.asm keeps its
bytes (bank $12 $4934, 106 records, byte-correct) but its header is
corrected to say it is NOT the stage table. That file is generated by
tools/generators/gen_slice7.py; the header fix lives there too (see the edit in
gen_slice7.py emit_bank18) so a regen stays truthful.

Outputs: src/banks/bank24.asm (new). Regenerate with:
  python3 tools/generators/gen_slice8.py
then update tools/generators/gen_banks.py CARVED (add 24: [(0x4934, 0x4C84)]),
regenerate src/banks.asm, add INCLUDE "bank24.asm" to src/main.asm,
and rebuild (byte-match arbitrates).
"""
import os
import re
import sys

sys.path.insert(0, "tools")
from gb_rd import walk, file_off  # noqa: E402

ROM = "roms/Donkey_Kong_World_Rev1_SGB.gb"
BANK = 24          # decimal; the game's "$18" bank
BASE = 0x4934
NREC = 106

# --- Bank $10 (decimal 16): the death path and its dispatchers ---------
BANK10 = 16
SEEDS10 = [0x51C8, 0x5349, 0x5664, 0x4031]
# Focused walk: 1179 instructions in 4 spans. The $51c8 routine is the
# per-frame update called from $0877 (state-16 timer code); the $52e0
# rst-$08 table (3 entries) and the $5405 rst-$08 table (17 entries)
# dispatch its handlers. $5349 is the death handler: $53c8 writes
# hStateTimer=12 (gb_watch, frame 2668, cycle 4184, A=$0c).
SPANS10 = [(0x4031, 0x4044), (0x51C8, 0x52E7),
           (0x52E7, 0x5428), (0x5428, 0x59F1)]
LABELS10 = {
    0x4031: "Bank10_4031",   # 19-byte routine; entry mechanism unverified
    0x51C8: "Bank10_51C8",   # per-frame update; called from $0877; reads [$dd18]
    0x52E0: "Bank10_Rst08_52E0",  # rst $08, 3-entry table ($5349,$53fc,$5664)
    0x5349: "Bank10_5349",   # death handler; $53c8 sets hStateTimer=12
    0x53FC: "Bank10_53FC",   # $52e0 table entry 1
    0x5405: "Bank10_Rst08_5405",  # rst $08, 17-entry table
    0x5428: "Bank10_5428",   # $5405 table entry 1
    0x549D: "Bank10_549D",
    0x5565: "Bank10_5565",
    0x55C1: "Bank10_55C1",
    0x5664: "Bank10_5664",   # $52e0 table entry 2; leads to $5349
    0x56CC: "Bank10_56CC",
    0x570C: "Bank10_570C",
    0x5750: "Bank10_5750",
    0x579B: "Bank10_579B",
    0x57CB: "Bank10_57CB",
    0x57CC: "Bank10_57CC",
    0x58A0: "Bank10_58A0",
    0x58BB: "Bank10_58BB",
    0x5918: "Bank10_5918",
    0x59D0: "Bank10_59D0",
    0x59D1: "Bank10_59D1",
    0x59E0: "Bank10_59E0",
}


def file_off(bank, addr):
    return bank * 0x4000 + (addr - 0x4000)


def jr_label10(tgt):
    return f"jr_010_{tgt:04x}"


def jr_targets10(instrs, lo, hi):
    out = set()
    for addr, (ln, text, kind, tgt) in instrs.items():
        if kind == "jr" and isinstance(tgt, int) and lo <= tgt <= hi:
            out.add(tgt)
    return out


def fmt_instr10(addr, text, kind, tgt, lo, hi, jr_targets):
    if addr in LABELS10:
        label = f"{LABELS10[addr]}::"
    elif addr in jr_targets:
        label = f"{jr_label10(addr)}:"
    else:
        label = None
    if kind == "jr" and isinstance(tgt, int) and lo <= tgt <= hi:
        tgt_label = LABELS10.get(tgt, jr_label10(tgt))
        text = re.sub(r"\$[0-9a-f]{4}$", tgt_label, text)
    line = f"    {text:<48} ; ${addr:04x}"
    return (label + "\n" + line) if label else line


def emit_bank10(rom):
    instrs, rst08, notes = walk(BANK10, SEEDS10)
    # Validate: every in-span control-flow target must be a decoded
    # instruction, and every rst-$08 entry must be decoded.
    for lo, hi in SPANS10:
        for addr, (ln, text, kind, tgt) in instrs.items():
            if kind in ("call", "jump", "jr") and isinstance(tgt, int) \
                    and lo <= tgt < hi and tgt not in instrs:
                print(f"ERROR: ${addr:04x} {text} targets ${tgt:04x}, "
                      f"not a decoded instruction", file=sys.stderr)
                sys.exit(1)
        for site, tbl in rst08.items():
            if not (lo <= site < hi):
                continue
            for i, w in enumerate(tbl):
                if 0x4000 <= w < 0x8000 and w not in instrs:
                    print(f"ERROR: rst $08 at ${site:04x} entry {i} -> "
                          f"${w:04x}, not decoded", file=sys.stderr)
                    sys.exit(1)
    out = ["; Slice 8: Bank $10 (decimal 16) -- the death path and its",
           "; dispatchers. The $51c8 routine is the per-frame update",
           "; called from $0877 (state-16 timer code); the $52e0 rst-$08",
           "; table (3 entries: $5349, $53fc, $5664) and the $5405",
           "; rst-$08 table (17 entries) dispatch its handlers. $5349",
           "; is the death handler: $53c8 writes hStateTimer=12, pinned",
           "; live by tools/harnesses/gb_watch (frame 2668, cycle 4184, A=$0c).",
           "; The $4031 span is a 19-byte routine whose entry mechanism",
           "; is unverified (it ran in the death-run ring before $0874).",
           "; Out-of-window targets $2b30/$2b3c are bank-0 routines",
           "; already carved in src/banks/bank0slice3.asm.",
           "; Generated by tools/generators/gen_slice8.py via tools/gb_rd.py.",
           "; Byte-match (`make`) arbitrates."]
    for lo, hi in SPANS10:
        out.append(f'SECTION "Bank $10 ${lo:04x}-${hi - 1:04x}", '
                   f'ROMX[${lo:04x}], BANK[{BANK10}]')
        jr_targets = jr_targets10(instrs, lo, hi)
        addr = lo
        while addr < hi:
            if addr in instrs:
                ln, text, kind, tgt = instrs[addr]
                if kind == "rst08":
                    tbl = rst08[addr]
                    out.append(f"    {'rst $08':<48} ; ${addr:04x}")
                    for i, w in enumerate(tbl):
                        out.append(f"    {'dw $%04x' % w:<48} ; entry {i}")
                    addr += 1 + 2 * len(tbl)
                    continue
                out.append(fmt_instr10(addr, text, kind, tgt, lo, hi, jr_targets))
                addr += ln
            else:
                run = []
                while addr < hi and addr not in instrs \
                        and not any(s < addr < s + 1 + 2 * len(t)
                                    for s, t in rst08.items()):
                    run.append(rom[file_off(BANK10, addr)])
                    addr += 1
                if not run:
                    print(f"ERROR: ${addr:04x}: fell into an rst-$08 table "
                          f"outside the rst08 branch", file=sys.stderr)
                    sys.exit(1)
                for j in range(0, len(run), 8):
                    chunk = run[j:j + 8]
                    out.append("    db " + ", ".join(f"${b:02x}" for b in chunk))
    return "\n".join(out) + "\n"


def emit_bank24(rom):
    out = ["; Slice 8: Bank $18 (decimal 24) $4934 stage table -- 106 8-byte records.",
           "; Read by $271e/$4586/$4807 (base $4934, stride 8, index B).",
           "; Layout VERIFIED (slice 8): [+0] world, [+5] world (dup, B<97),",
           "; [+6] stage-in-world. Proof: gb_watch shows the $2745/$2750",
           "; writes during the state-20 timer-1 map visit read record B=0",
           "; as (world,stage)=(1,1); bank $18 record 0 is",
           "; `01 80 20 60 80 01 01 05`. B=0..96 are clean: worlds 1-9,",
           "; stages 1-8/12/16 in order. [+1..+4] coordinate-like pairs",
           "; and [+7] (4-40) are unresolved. B=97..105 do NOT fit the",
           "; pattern (worlds 0/110/62/28) -- role unresolved; the queue",
           "; does hold C==1 entries with B=97..100, so they may be live.",
           "; Slice 7 carved bank 18 DECIMAL here by a decimal/hex slip;",
           "; that file (src/banks/bank18.asm) is bank $12 data, NOT this table.",
           "; Generated by tools/generators/gen_slice8.py from the ROM bytes.",
           'SECTION "Bank $18 $4934 stage table", ROMX[$4934], BANK[24]']
    off = file_off(BANK, BASE)
    for i in range(NREC):
        chunk = rom[off + 8 * i: off + 8 * i + 8]
        if i < 97:
            note = " ; B=%d world %d stage %d" % (i, chunk[0], chunk[6])
        else:
            note = " ; B=%d NON-STAGE pattern ([0]=%d [6]=%d)" % (i, chunk[0], chunk[6])
        out.append("    db " + ", ".join(f"${b:02x}" for b in chunk) + note)
    return "\n".join(out) + "\n"


def main():
    rom = open(ROM, "rb").read()
    header = ("; DO NOT HAND-EDIT the code bodies in this file -- regenerate with\n"
              ";   python3 tools/generators/gen_slice8.py\n"
              "; after changing the generator config. Entry labels and comments\n"
              "; may be added by hand above a generated block, not inside it.\n\n")
    with open("src/banks/bank24.asm", "w") as f:
        f.write(header + emit_bank24(rom))
    print("wrote src/banks/bank24.asm (106 records)")
    with open("src/banks/bank10.asm", "w") as f:
        f.write(header + emit_bank10(rom))
    print("wrote src/banks/bank10.asm (4 spans, 1179 instructions)")


if __name__ == "__main__":
    main()
